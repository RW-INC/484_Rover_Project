def multiple_runs(n_sims, landing_sigma_m):
    def landing_site_error(mission_site, landing_sigma_m, traversable_grid):
        # introduce Gaussian error in landing site
        cx, cy, trav_percent, elev_std = mission_site
        landing_sigma_px = landing_sigma_m / 10  # convert from meters to pixels
        for _ in range(100):  # try until we land on traversable terrain
            new_cx = int(np.random.normal(cx, landing_sigma_px))
            new_cy = int(np.random.normal(cy, landing_sigma_px))
            new_cx = np.clip(new_cx, 0, traversable_grid.shape[1]-1)
            new_cy = np.clip(new_cy, 0, traversable_grid.shape[0]-1)

            if traversable_grid[new_cy, new_cx]:
                break

        actual_lander = (new_cy, new_cx)  # this IS the lander position
        new_mission_site = (new_cx, new_cy, trav_percent, elev_std)
        return new_mission_site, actual_lander

    results = []
    failures = {"no_waypoints": 0, "no_path": 0, "planner_timeout": 0}

    # 1. USER INPUTS
    region_size = 25000 # meters
    major_axis = 1.1 # km
    minor_axis = 1.1
    distance_range_m = [50, 1000]
    stop_locations = 3

    # 2. PRE-SET SAVED LANDER LOCATION IF DESIRED
    PRESET_MISSION_REGION = True # use ORIGINAL_START as the goal lander location and determine center of mission site
    ORIGINAL_START = (18500, 16500) # meters from true South
    CONSTANT_WAYPOINTS = False # attempt to reach same waypoints CONSTANT mission region every time

    # original_start = (16010, 17800)

    # 3. LOAD DATA AND GENERATE TRAVERSABILITY GRID
    elevation, slopes, sun_data, avg_sun, transform = load_data(ELEV_FILE, SLOPE_FILE, region_size)
    traversable_grid = traversability(elevation, slopes, avg_sun)
    wp_generator = GenerateWaypoints(major_axis, minor_axis, traversable_grid, elevation)

    # 4. SET MISSION SITE BY EITHER ITERATING THROUGH REGIONS OR USING USER-INPUT FOR LANDER LOCATION
    if not PRESET_MISSION_REGION:
        viable_sites = wp_generator.find_landing_ellipses()
        mission_site_original = viable_sites[np.random.randint(0,5)] # choose one of top three landing sites
    else:
        viable_sites = []
        # convert original_start from meters to pixel (row, col)
        inv_transform = ~transform
        col, row = inv_transform*ORIGINAL_START
        original_start_px = (int(row), int(col))
        mission_site_original = (original_start_px[1], original_start_px[0], 1, 10) # centered around start waypoint for now, the other two values aren't accurate so deleted them

    if CONSTANT_WAYPOINTS:
      preset_wps = wp_generator.choose_waypoints(avg_sun, distance_range_m, mission_site_original, original_start_px, stop_locations)

    # 5. LOOP THROUGH SIMULATION RUNS, CHANGING LANDING SITE ERROR AT EACH RUN
    for sim in range(n_sims):
        # 6. PRETURB LANDING SITE
        mission_site, start = landing_site_error(mission_site_original, landing_sigma_m, traversable_grid) # include Gaussian uncertainty for landing site

        # commented this out to help with algorithm convergence and computational efficiency
        los_map = wp_generator.precompute_los_map_downsampled(elevation, start, mission_site, major_axis, minor_axis, downsample=5)

        sim_grid = traversable_grid & los_map

        # 7. EITHER CHOOSE NEW WAYPOINTS BASED ON UPDATED LANDING REGION OR ATTEMPT TO FIND A PATH WITH OLD WAYPOINTS
        if not CONSTANT_WAYPOINTS:
          waypoints = wp_generator.choose_waypoints(avg_sun, distance_range_m, mission_site, start, stop_locations)
        else:
          waypoints = [start] + preset_wps[1:] # add pre set waypoints after starting location
          mission_site = mission_site_original

        if waypoints is None:
            print(f'Simulation {sim+1}: Failure to determine viable waypoints. Skipping to next sim iteration.')
            failures["no_waypoints"] += 1
            continue

        # start = waypoints[0]
        goal = waypoints[-1]

        world = TerrainWorld(sim_grid)
        size = sim_grid.shape[0]

        # 8. ENSURE ALL WAYPOINTS ARE CONNECTED
        connected = True
        if not CONSTANT_WAYPOINTS:
          connected = False
          for attempt in range(5):
              connected = True  # assume valid until proven otherwise
              for i in range(len(waypoints) - 1):
                  if not path_exists(world, waypoints[i], waypoints[i+1]):
                      print("No valid rover path between start and goal. Choosing new waypoints...")
                      connected = False
                      break
              if connected:
                  break  # there is a possible path
              # regenerate waypoints if failed
              waypoints = wp_generator.choose_waypoints(avg_sun, distance_range_m, mission_site, start, stop_locations)
              if waypoints is None:
                print(f'Simulation {sim+1}: Failure to determine viable waypoints. Skipping to next sim iteration.')
                failures["no_waypoints"] += 1
                continue

        if not connected:
            print(f"Simulation {sim+1}: no valid path, skipping.")
            failures["no_path"] += 1
            continue

        # 9. PLAN D* PATH ACROSS CONSECUTIVE WAYPOINTS
        full_path = []
        current_start = start

        for wp in waypoints[1:]:
            planner = DStarLite(size, current_start, wp, start, elevation, avg_sun)
            planner.compute_shortest_path(world)

            segment = extract_path(planner, world, current_start, wp)

            if segment is not None:
                if full_path:
                    full_path.extend(segment[1:])
                else:
                    full_path.extend(segment)
                current_start = wp

        total_distance = calculate_path_distance(full_path)
        if current_start != goal or total_distance == 0:
            print(f"Simulation {sim+1}: no valid path, skipping.")
            failures["no_path"] += 1
            continue

        # 10. OUTPUT SIM RUN RESULTS
        print(f"====Simulation {sim+1} Results =====")
        total_distance, comm_fraction, straight_distance, max_radial_dist, sun_fraction, longest_los_m, elevation_range_m, longest_sun_loss_m = compute_metrics(full_path, waypoints, elevation, sun_data)
        if CONSTANT_WAYPOINTS:
          land_error = np.linalg.norm(np.array(start[:2]) - np.array(original_start_px[:2])) * 10
        else:
          land_error = np.linalg.norm(np.array(mission_site_original[:2][::-1]) - np.array(mission_site[:2][::-1]))*10
        results.append({
            "Simulation": sim+1,
            "Mission_Site": mission_site,
            "Waypoints": waypoints,
            "Path": full_path,
            "Distance": total_distance, ###
            "Distance_from_lander": straight_distance,
            "Max_radial_distance": max_radial_dist,
            "Sun_fraction": sun_fraction, ###
            "Percent_LOS": comm_fraction, ###
            "landing_error_m": land_error, ##
            "longest_los_m":  longest_los_m, # loss
            "elevation_range_m": elevation_range_m,
            "longest_sun_loss_m": longest_sun_loss_m})
        print(f'Landing error: {land_error} m')

    print('\n=====OVERALL MONTE CARLO RESULTS=====\n')
    print(f'Region Size = {region_size} m --- Major Axis = {major_axis} m --- Minor Axis = {minor_axis}')
    success_rate = len(results) / n_sims
    print(f"\nSuccess rate: {success_rate*100:.1f}%")
    print(f"Failures: {failures}\n")

    best_sims = sorted(results, key=lambda x: x["Percent_LOS"], reverse=True)[:3]
    for sim in best_sims:
        print(f'\nSimulation #{sim["Simulation"]}')
        print(f"Percent LOS on path: {sim["Percent_LOS"]*100}")
        store_path_results(sim["Path"], sim["Waypoints"], format="METERS")
        store_path_results(sim["Path"], sim["Waypoints"], format="PIXELS")

    if results:
        plotter = AnalyzePlotPaths(world, full_path, transform)
        plotter.overall_monte_carlo_plot(results, n_sims, failures)



