def compute_metrics(full_path, waypoints, elevation, sun_data):
      total_distance = calculate_path_distance(full_path)

      # straight line distance
      straight_distance = np.linalg.norm(np.array(waypoints[-1]) - np.array(waypoints[0])) * 10  # pixels to meters

      # LOS / communication fraction
      los_count = sum(line_of_sight(elevation, node, waypoints[0]) for node in full_path)
      comm_fraction = los_count / len(full_path)

      # max radial distance from lander
      max_radial_dist = max(np.linalg.norm(np.array(node) - np.array(waypoints[0])) * 10 for node in full_path)

      # longest loss of LOS segment
      max_loss_streak = 0
      current_loss_streak = 0
      for node in full_path:
          if not line_of_sight(elevation, node, waypoints[0]):
              current_loss_streak += 1
              max_loss_streak = max(max_loss_streak, current_loss_streak)
          else:
              current_loss_streak = 0
      longest_los_loss_m = max_loss_streak * 10

      # longest loss of sunlight
      # longest continuous loss of sunlight
      max_sun_loss_streak = 0
      current_sun_loss_streak = 0
      total_time = 0
      sun_window_time = 10 * 3600
      rover_speed = 0.02
      meters_per_pixel = 10
      time_per_pixel = meters_per_pixel / rover_speed
      total_time = 0
      sun_count = 0

      for y, x in full_path:
          sun_idx = min(int(total_time / sun_window_time), sun_data.shape[2] - 1)
          if sun_data[y, x, sun_idx] < 0.9:
              current_sun_loss_streak += 1
              max_sun_loss_streak = max(max_sun_loss_streak, current_sun_loss_streak)
          else:
              current_sun_loss_streak = 0
          total_time += time_per_pixel

      longest_sun_loss_m = max_sun_loss_streak * 10

      # elevation range
      elevations = [elevation[y, x] for y, x in full_path]
      elevation_range_m = max(elevations) - min(elevations)

      # use time-resolved data like in plot_illumination_path
      rover_speed = 0.02
      meters_per_pixel = 10
      time_per_pixel = meters_per_pixel / rover_speed
      sun_window_time = 10 * 3600
      total_time = 0
      sun_count = 0

      for y, x in full_path:
          sun_idx = min(int(total_time / sun_window_time), sun_data.shape[2] - 1)
          if sun_data[y, x, sun_idx] >= 0.9:
              sun_count += 1
          total_time += time_per_pixel

      sun_fraction = sun_count / len(full_path)

      np.set_printoptions(precision=3)
      print(f"====Simulation Results =====")
      print(f"Waypoints: {waypoints}")
      print(f"Distance Traveled: {total_distance} m")
      print(f"Ending Distance from Lander: {straight_distance} m")
      print(f'Maximum Radial Distance: {max_radial_dist} m')
      print(f'Percent sun on path: {sun_fraction*100}%')
      print(f"Percent LOS on path: {comm_fraction*100}%")
      print(f'Longest LOS loss m: {longest_los_loss_m} m')
      print(f'Longest sun loss: {longest_sun_loss_m} m')
      print(f'Elevation range: {elevation_range_m} m')

      return total_distance, comm_fraction, straight_distance, max_radial_dist, sun_fraction, longest_los_loss_m, elevation_range_m, longest_sun_loss_m

