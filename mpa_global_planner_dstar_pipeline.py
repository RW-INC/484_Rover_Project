# D*
class DStarLite:
    def __init__(self, size, start, goal, lander, elevation, illumination):
        # inits
        self.size = size
        self.start = start
        self.goal = goal
        self.lander = lander
        self.elevation = elevation
        self.illumination = illumination
        self.g = {}
        self.rhs = {}
        self.U = []
        self.in_queue = {}
        self.km = 0
        self.time_per_px_s = 200 # 10 m / 0.02 m /s speed

        self.rhs[self.goal] = 0
        initial_key = self.calculate_key(self.goal)
        self.in_queue[self.goal] = initial_key
        heapq.heappush(self.U, (initial_key, self.goal))

    def heuristic(self, a, b):
        dx = abs(a[0] - b[0])
        dy = abs(a[1] - b[1])
        return max(dx, dy) + (math.sqrt(2) - 1) * min(dx, dy)

    def calculate_key(self, s):
        k1 = min(self.g.get(s, INF), self.rhs.get(s,INF)) + self.heuristic(self.start, s) + self.km
        k2 = min(self.g.get(s, INF), self.rhs.get(s,INF))
        return (k1, k2)

    def neighbors(self, s, world):
        x, y = s
        results = []
        for dx in [-1, 0, 1]:
            for dy in [-1, 0, 1]:
                if dx == 0 and dy == 0:
                    continue
                nx, ny = x+dx, y+dy
                if 0 <= nx < self.size and 0 <= ny < self.size:
                    if dx != 0 and dy != 0: # prevent corner cutting
                        if world.is_obstacle(x + dx, y) or world.is_obstacle(x, y + dy):
                            continue
                    results.append((nx, ny))
        return results

    def cost(self, u, v, world):
        # if either is an obstacle, cost is infinite
        if world.is_obstacle(*u) or world.is_obstacle(*v):
            return INF

        # distance cost (diagonal vs straight)
        dx = abs(u[0] - v[0])
        dy = abs(u[1] - v[1])

        if dx == 1 and dy == 1:
            dist_cost = math.sqrt(2)
        else:
            dist_cost = 1

        # LOS penalty
        if fast_line_of_sight(self.elevation, v, self.lander):
            los_penalty = 0 # there is LOS
        else:
            los_penalty = 5

        y, x = v

        # solar illumination penalty
        if self.illumination[y,x] >= 0.2:
            solar_penalty = 0
        else:
            solar_penalty = 5

        return dist_cost + los_penalty + solar_penalty

        # return dist_cost

    def update_vertex(self, u, world):
        if u != self.goal:
            # rhs(u) = min_{s' in nbrs} (c(u, s') + g(s'))
            costs = []
            for s_prime in self.neighbors(u, world):
                costs.append(self.cost(u, s_prime, world) + self.g.get(s_prime, INF))
            self.rhs[u] = min(costs) if costs else INF

        if self.g.get(u, INF) != self.rhs.get(u, INF):
            key = self.calculate_key(u)
            if self.in_queue.get(u) != key:
                self.in_queue[u] = key
                heapq.heappush(self.U, (key, u))
        elif u in self.in_queue:
            del self.in_queue[u]

    def compute_shortest_path(self, world):
        iterations = 0
        while self.U and (
        self.U[0][0] < self.calculate_key(self.start) or
        self.rhs.get(self.start, INF) != self.g.get(self.start, INF)):
            k_old, u = heapq.heappop(self.U)
            k_new = self.calculate_key(u)
            if self.in_queue.get(u) != k_old:
                continue

            iterations += 1
            if iterations >= 100000:
                break
            if iterations % 5000 == 0:
                print(f"D* iteration {iterations}, queue size: {len(self.U)}")
            if k_old < k_new:
                self.in_queue[u] = k_new
                heapq.heappush(self.U, (k_new, u))
            elif self.g.get(u, INF) > self.rhs.get(u, INF):
                self.g[u] = self.rhs[u]
                for s in self.neighbors(u, world):
                    self.update_vertex(s, world)
            else:
                self.g[u] = INF
                self.update_vertex(u, world)
                for s in self.neighbors(u, world):
                    self.update_vertex(s, world)

def load_data(elevation_file, slope_file, region_size):
    # elevation data
    with rasterio.open(elevation_file) as src:
        window = from_bounds(-region_size, -region_size, region_size, region_size, src.transform)
        elevation = src.read(1, window = window)
        el_shape = elevation.shape
        transform = src.window_transform(window)

    # slopes data
    with rasterio.open(slope_file) as src:
        window = from_bounds(-region_size, -region_size, region_size, region_size, src.transform)
        slopes = src.read(1, window = window)

    # solar illumination data
    data = loadmat(SUN_FILE)

    sun = data["all_sun_data"]   # (ny, nx, nt)
    X = data["X"]
    Y = data["Y"]

    # crop to same region size as elevation
    x_min, x_max = -region_size, region_size
    y_min, y_max = -region_size, region_size

    x_mask = (X[0, :] >= x_min) & (X[0, :] <= x_max)
    y_mask = (Y[:, 0] >= y_min) & (Y[:, 0] <= y_max)

    sun_cropped = sun[y_mask, :, :]
    sun_cropped = sun_cropped[:, x_mask, :]

    # resample time slices to match elevation resolutions
    rows, cols = el_shape
    nt = sun_cropped.shape[2]

    sun_resampled = np.zeros((rows, cols, nt))

    for t in range(nt):
        sun_resampled[:, :, t] = cv2.resize(sun_cropped[:, :, t], (cols, rows), interpolation=cv2.INTER_NEAREST)

    # avg sunlight metric
    avg_sun = np.mean(sun_resampled, axis=2)

    return elevation, slopes, sun_resampled, avg_sun, transform

def traversability(elevation, slopes, avg_sun):
    # traversable terrain
    traversable_slopes = slopes < 10

    traversable_sun = avg_sun >= 0.50

    # combine traversable regions
    traversable = traversable_slopes & traversable_sun

    return traversable

def fast_line_of_sight(elevation, point1, point2):
    y0, x0 = point1
    y1, x1 = point2

    z0 = elevation[y0, x0] + 0.042
    z1 = elevation[y1,x1] + 2.5

    dx = x1 - x0
    dy = y1 - y0
    dz = z1 - z0

    num_checks = 15

    # coarse pass
    for i in range(1, num_checks + 1):

        t = i / (num_checks + 1)

        x = int(round(x0 + dx*t))
        y = int(round(y0 + dy*t))

        z_expected = z0 + dz * t
        z_actual = elevation[y, x]

        if z_actual > z_expected:
            return False
    return True

def line_of_sight(elevation, point1, point2):
    y0, x0 = point1
    y1, x1 = point2

    z0 = elevation[y0, x0] + 0.042
    z1 = elevation[y1,x1] + 1

    dx = x1 - x0
    dy = y1 - y0
    dz = z1 - z0

    step_size = int(max(abs(dx), abs(dy)))

    # fine pass
    for i in range(1, step_size):

        if step_size == 0:
            return True

        t = i / step_size

        x = int(round(x0 + dx*t))
        y = int(round(y0 + dy*t))

        z_expected = z0 + dz * t
        z_actual = elevation[y, x]

        if z_actual > z_expected:
            return False

    return True

