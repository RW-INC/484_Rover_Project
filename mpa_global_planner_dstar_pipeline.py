    """
    Calculates whether the rover is in sunlight or shade at the time t it is traversing a certain
    pixel on the pre-determined D* path. Based on the rover travelling 2 cm/s, or 10/0.02 = 200 seconds to traverse each pixel.
    """
    def plot_illumination_path(self, sun_data, avg_sun, full_path, waypoints):
        x_min, x_max, y_min, y_max = self.axis_limits

        fig, ax = plt.subplots(figsize=(8, 4))

        # --- Base layer: solar illumination heatmap ---
        h, w = avg_sun.shape[:2]
        x_min_m, y_max_m = self.transform*(0, 0)
        x_max_m, y_min_m = self.transform*(w, h)
        extent = [x_min_m/1000, x_max_m/1000, y_min_m/1000, y_max_m/1000]

        im = ax.imshow(avg_sun, cmap='inferno', extent=extent)

        cbar = plt.colorbar(im, ax=ax)
        cbar.set_label("Average Sunlight (%)")

        ax.grid(True, linestyle='--', alpha=0.5)

        rover_speed = 0.02  # m/s
        meters_per_pixel = 10
        time_per_pixel = meters_per_pixel / rover_speed  # 500 sec per pixel
        sun_window_time = 10 * 3600  # 10 hours in seconds

        total_time = 0

        # --- Overlay path colored by sunlight at time t ---
        for i in range(len(full_path) - 1):
            p1 = full_path[i]
            p2 = full_path[i+1]

            total_time += time_per_pixel

            sun_idx = int(total_time / sun_window_time)
            sun_idx = min(sun_idx, sun_data.shape[2] - 1)

            y, x = p1

            if sun_data[y, x, sun_idx] >= 0.75:
                color = 'green'
            else:
                color = 'black'

            x1_km, y1_km = self.px_to_km(p1[0], p1[1])
            x2_km, y2_km = self.px_to_km(p2[0], p2[1])
            ax.plot([x1_km, x2_km], [y1_km, y2_km], color=color, linewidth=2)

        # --- Draw waypoints ---
        for i, wp in enumerate(waypoints):
            y, x = wp
            x_km, y_km = self.px_to_km(y, x)
            circle = plt.Circle((x_km, y_km), radius=0.05, color='blue', fill=True)
            ax.add_patch(circle)
            ax.text(x_km + 0.02, y_km + 0.02, f"WP{i+1}", color='blue', fontsize = 12)

        ax.set_xlabel("X (kilometers from lunar south pole)")
        ax.set_ylabel("Y (kilometers from lunar south pole)")
        ax.set_aspect('equal')
        x_min_lim, x_max_lim, y_min_lim, y_max_lim = self.px_limits_to_km()
        ax.set_xlim(x_min_lim, x_max_lim)
        ax.set_ylim(y_min_lim, y_max_lim)
